const dicts: Record<Language, Dict> = { en, zh };

// Look up a string, with {name} interpolation. Falls back to English, then to
// the key itself, so a missing Chinese entry never blanks the UI.
export function t(key: string, vars?: Record<string, string | number>): string {
  const raw = dicts[getLanguage()][key] ?? en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

// Hook version: re-renders the component when the language changes. The returned
// function gets a new identity on a language change, so useMemo/useCallback blocks
// that list it in their deps recompute with the new language.
export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const [lang] = useLanguage();
  // `lang` is intentionally the only dep: the module-level t() reads the current
  // language itself, but the new identity is what makes memos recompute on switch.
  // eslint-disable-next-line react-hooks/exhaustive-deps
  return useCallback((key: string, vars?: Record<string, string | number>) => t(key, vars), [lang]);
}
